let dbCache: DatabaseSchema | null = null;

export function getDb(): DatabaseSchema {
  if (dbCache) return dbCache;
  fs.mkdirSync(DB_DIR, {recursive: true});
  if (fs.existsSync(DB_PATH)) {
    try {
      const raw = fs.readFileSync(DB_PATH, 'utf8');
      dbCache = JSON.parse(raw) as DatabaseSchema;
      return dbCache;
    } catch {
      // Fall back to fresh seed if file is corrupted
    }
  }
  dbCache = createSeedData();
  saveDb(dbCache);
  return dbCache;
}

export function saveDb(nextDb: DatabaseSchema): void {
  dbCache = nextDb;
  fs.mkdirSync(DB_DIR, {recursive: true});
  const tmpPath = `${DB_PATH}.${process.pid}.tmp`;
  fs.writeFileSync(tmpPath, JSON.stringify(nextDb, null, 2), 'utf8');
  fs.renameSync(tmpPath, DB_PATH);
}

